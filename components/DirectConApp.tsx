export default function DirectConApp() {
  const [config, setConfig] = useState<Config>(() => loadConfig());
  const [simType, setSimType] = useState<SimType | null>(null);
  const [configOpen, setConfigOpen] = useState(false);
  const [selectedMode, setSelectedMode] = useState<SimType | null>(null);
  const [step, setStep] = useState(0);
  const [direction, setDirection] = useState(1);

  const [nome, setNome] = useState('');
  const [consultor, setConsultor] = useState('');
  const [nomeTouched, setNomeTouched] = useState(false);

  const consultores = useMemo(
    () => [...config.consultores].sort((a, b) => a.localeCompare(b, 'pt-BR')),
    [config.consultores]
  );

  useEffect(() => {
    if (!consultor && consultores.length > 0) setConsultor(consultores[0]);
  }, [consultores]);

  const steps = simType === 'detalhada' ? DETALHADA_STEPS : RAPIDA_STEPS;
  const totalSteps = steps.length;

  useEffect(() => { setStep(0); setDirection(1); }, [simType]);

  const goToStep = useCallback((target: number) => {
    setDirection(target > step ? 1 : -1);
    setStep(target);
  }, [step]);

  const nomeError = nomeTouched && nome.trim().length === 0 ? 'Informe o nome do cliente' : '';

  function handleComecar() {
    if (nome.trim().length === 0) { setNomeTouched(true); return; }
    if (!selectedMode) return;
    setDirection(1);
    setSimType(selectedMode);
    setStep(0);
  }

  function handleBack() {
    if (step > 0) {
      goToStep(step - 1);
    } else {
      setDirection(-1);
      setSimType(null);
    }
  }

  // ── Tela inicial ──
  if (simType === null) {
    return (
      <div className="app-shell">
        <div className="app-card" style={{ position: 'relative' }}>
          <AnimatePresence>
            {configOpen && (
              <ConfigPanel
                key="config"
                config={config}
                onSave={cfg => { setConfig(cfg); setConfigOpen(false); }}
                onClose={() => setConfigOpen(false)}
              />
            )}
          </AnimatePresence>

          {/* ── Top bar ── */}
          <div className="home-topbar">
            <Logo />
            <button
              className="home-topbar__gear"
              onClick={() => setConfigOpen(true)}
              aria-label="Configurações"
            >
              <Settings size={18} />
            </button>
          </div>

          <motion.div
            className="screen-content"
            key="home"
            initial={{ opacity: 0, y: 8 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.2, ease: EASE }}
          >
            <div className="step-body">
            <div className="step-inner">
              <div className="home-header">
                <h1 className="step-title">Faça uma simulação</h1>
                <p className="step-subtitle">
                  Preencha os dados abaixo para calcular as parcelas e condições do seu consórcio.
                </p>
              </div>

              <div className="fields-stack">
                <div className={`fg${nomeError ? ' fg--error' : ''}`}>
                  <label htmlFor="nome">Nome do cliente</label>
                  <input
                    id="nome" type="text" autoComplete="name"
                    placeholder="Ex: João Silva"
                    value={nome}
                    onChange={e => setNome(e.target.value)}
                    onBlur={() => setNomeTouched(true)}
                    aria-invalid={!!nomeError}
                  />
                  <FieldError msg={nomeError} />
                </div>

                <div className="fg">
                  <label htmlFor="consultor">Consultor responsável</label>
                  <div className="select-wrap">
                    <select
                      id="consultor"
                      value={consultor}
                      onChange={e => setConsultor(e.target.value)}
                    >
                      {consultores.map(c => <option key={c}>{c}</option>)}
                    </select>
                    <span className="select-arrow"><ChevronDown size={16} /></span>
                  </div>
                </div>
              </div>

              <div className="fg">
                <label>Escolha a modalidade</label>
                <div className="sel-cards-row">
                  {MODE_CARDS.map(card => (
                    <button
                      key={card.id}
                      type="button"
                      className={`sel-card sel-card--tall${selectedMode === card.id ? ' active' : ''}`}
                      onClick={() => setSelectedMode(card.id)}
                    >
                      <span className="sel-card__icon">
                        {card.icon}
                      </span>
                      <span className="sel-card__title">{card.title}</span>
                      <span className="sel-card__desc">{card.desc}</span>
                    </button>
                  ))}
                </div>
              </div>
            </div>
          </div>
          </motion.div>

          <div className="step-footer">
            <button
              className="btn btn-gold btn-full"
              onClick={handleComecar}
              disabled={!selectedMode}
            >
              Começar
            </button>
          </div>
        </div>
      </div>
    );
  }

  // ── Telas do wizard ──
  return (
    <div className="app-shell">
      <div className="app-card">
        <AnimatePresence mode="wait">
          {simType === 'rapida' && (
            <motion.div
              key={`rapida-${step}`}
              className="screen-content"
              initial={{ opacity: 0, x: direction * 30 }}
              animate={{ opacity: 1, x: 0 }}
              exit={{ opacity: 0, x: direction * -30 }}
              transition={{ duration: 0.25, ease: EASE }}
            >
              <TabRapida
                config={config}
                consultores={consultores}
                step={step}
                onStepChange={goToStep}
                direction={direction}
                nome={nome}
                consultor={consultor}
                onBack={handleBack}
                totalSteps={totalSteps}
              />
            </motion.div>
          )}
          {simType === 'detalhada' && (
            <motion.div
              key={`detalhada-${step}`}
              className="screen-content"
              initial={{ opacity: 0, x: direction * 30 }}
              animate={{ opacity: 1, x: 0 }}
              exit={{ opacity: 0, x: direction * -30 }}
              transition={{ duration: 0.25, ease: EASE }}
            >
              <TabDetalhada
                config={config}
                consultores={consultores}
                step={step}
                onStepChange={goToStep}
                direction={direction}
                nome={nome}
                consultor={consultor}
                onBack={handleBack}
                totalSteps={totalSteps}
              />
            </motion.div>
          )}
        </AnimatePresence>
      </div>
    </div>
  );
}
